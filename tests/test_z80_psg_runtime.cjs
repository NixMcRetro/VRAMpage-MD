'use strict';
const assert = require('node:assert/strict');
const path = require('node:path');

const [runtimePath, normalPath] = process.argv.slice(2).map(value => path.resolve(value));
if (!runtimePath || !normalPath) throw new Error('Pass runtime and normal genplus.js paths.');

function locate(file) {
  return {locateFile: name => path.join(path.dirname(file), name)};
}

function z80ToneCartridge() {
  const rom = new Uint8Array(0x10000);
  const view = new DataView(rom.buffer);
  for (let offset = 0; offset < 0x100; offset += 4) view.setUint32(offset, 0x300);
  view.setUint32(0, 0xffff00);
  view.setUint32(4, 0x200);
  rom.set(Buffer.from('SEGA MEGA DRIVE '), 0x100);
  rom.set(Buffer.from('VRAMPAGE Z80 PSG TEST'), 0x120);
  view.setUint32(0x1a4, rom.length - 1);
  view.setUint32(0x1a8, 0xff0000);
  view.setUint32(0x1ac, 0xffffff);
  rom[0x1f0] = 0x55;

  // Z80 LD A,n / LD (nn),A sends PSG bytes via $7F11.
  const z80 = [
    0x3e, 0x8a, 0x32, 0x11, 0x7f,
    0x3e, 0x10, 0x32, 0x11, 0x7f,
    0x3e, 0x90, 0x32, 0x11, 0x7f,
    0x18, 0xfe
  ];

  const words = [];
  const word = (address, value) => words.push(0x33fc, value, address >>> 16, address & 0xffff);
  const byte = (address, value) => words.push(0x13fc, value, address >>> 16, address & 0xffff);

  // On reset the Z80 starts held. Assert BUSREQ, release RESET while BUSREQ
  // remains active, copy the program into Z80 RAM through the granted A0 bus,
  // then release BUSREQ so the Z80 executes it. No 68K store targets the PSG.
  word(0x00a11100, 0x0100);
  word(0x00a11200, 0x0100);
  z80.forEach((value, index) => byte(0x00a00000 + index, value));
  word(0x00a11100, 0x0000);
  words.push(0x60fe); // Keep the 68K alive while the Z80 runs.

  // The 68K bootstrap writes only the bus-control registers and Z80 RAM.
  assert.equal(words.includes(0xc00011), false);
  words.forEach((value, index) => view.setUint16(0x200 + index * 2, value));
  [0x4e72, 0x2700, 0x60fe].forEach((value, index) => view.setUint16(0x300 + index * 2, value));
  return rom;
}

async function createCore(file, rom) {
  const core = await require(file)(locate(file));
  core._init();
  core.HEAPU8.set(rom, core._get_rom_buffer_ref(rom.length));
  core._start();
  new Float32Array(core.HEAPF32.buffer, core._get_input_buffer_ref(), 32).fill(0);
  return core;
}

function nextAudio(core) {
  core._wasm_input_update();
  core._tick();
  const count = core._sound();
  const left = core._get_web_audio_l_ref() >>> 2;
  const right = core._get_web_audio_r_ref() >>> 2;
  return {
    count,
    left: Float32Array.from(core.HEAPF32.subarray(left, left + count)),
    right: Float32Array.from(core.HEAPF32.subarray(right, right + count))
  };
}

async function main() {
  const rom = z80ToneCartridge();
  const normal = await createCore(normalPath, rom);
  assert.equal(typeof normal._set_psg_data_bridge, 'undefined',
    'normal core has no PSG input API');
  const baseline = nextAudio(normal);
  assert.ok(baseline.count > 0, 'Z80 program produces audio samples');
  assert.ok([...baseline.left, ...baseline.right].every(Number.isFinite));
  assert.ok([...baseline.left, ...baseline.right].some(value => Math.abs(value) > 0.0001),
    'Z80-origin PSG writes produce nonzero audio');

  const off = await createCore(runtimePath, rom);
  assert.equal(typeof off._set_psg_data_bridge, 'function');
  const offSamples = nextAudio(off);
  const offState = off._get_psg_data_bridge_state();
  assert.equal(offSamples.count, baseline.count, 'runtime-off sample count matches normal');
  assert.deepEqual(offSamples.left, baseline.left, 'runtime-off left samples match normal');
  assert.deepEqual(offSamples.right, baseline.right, 'runtime-off right samples match normal');
  assert.equal(offState.inputWrites, '0', 'runtime-off Z80 writes do not count as bridged');

  const active = await createCore(runtimePath, rom);
  assert.equal(active._set_psg_data_bridge(1, 0, 7), 0);
  const activeSamples = nextAudio(active);
  const activeState = active._get_psg_data_bridge_state();
  assert.equal(activeSamples.count, baseline.count, 'active bridge preserves sample count');
  assert.ok([...activeSamples.left, ...activeSamples.right].every(Number.isFinite));
  assert.ok(BigInt(activeState.inputWrites) > 0n,
    'Z80 writes through $7F11 reach the runtime PSG sink');
  assert.ok(BigInt(activeState.changedWrites) > 0n,
    'the bridge changes bytes supplied by the Z80');
  assert.equal(activeState.inputWrites, '3',
    'the sink sees exactly the three stores in the Z80 test program');
  assert.equal(activeState.changedWrites, '2',
    'the selected inputs change exactly the latch and volume bytes');
  assert.notDeepEqual(activeSamples.left, baseline.left,
    'active bridge changes audio generated by Z80 PSG writes');

  const reset = await createCore(runtimePath, rom);
  assert.equal(reset._set_psg_data_bridge(1, 0, 7), 0);
  const changed = nextAudio(reset);
  assert.ok(BigInt(reset._get_psg_data_bridge_state().inputWrites) > 0n);
  reset.HEAPU8.set(rom, reset._get_rom_buffer_ref(rom.length));
  reset._start();
  const resetState = reset._get_psg_data_bridge_state();
  assert.equal(resetState.configured, false, 'cartridge restart clears bridge configuration');
  assert.equal(resetState.inputWrites, '0', 'cartridge restart clears bridge counters');
  const restored = nextAudio(reset);
  assert.equal(restored.count, baseline.count);
  assert.deepEqual(restored.left, baseline.left,
    'reset restores normal future Z80 PSG writes');
  assert.notDeepEqual(changed.left, restored.left,
    'reset does not erase the observed active-bridge audio difference');
  console.log('Z80 $7F11 PSG writes matched normal while runtime-off, changed tone while active, and reset cleanly.');
}

main().catch(error => { console.error(error); process.exitCode = 1; });
